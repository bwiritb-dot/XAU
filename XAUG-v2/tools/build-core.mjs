// Собирает src/core.js из оригинального app.js: функции копируются побайтно.
// Запуск: node tools/build-core.mjs
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
export const APP_JS = path.resolve(here, "../../app.js");
export const CORE_JS = path.resolve(here, "../src/core.js");

export const FUNCTIONS = [
  "calculateIndicators",
  "calculateATR",
  "isDeathZone",
  "classifyCandleWick",
  "calculateBreakoutProbability",
  "calculateMeanReversionProbability",
  "calculateWSBOrderFlow",
  "updateTradeMarkers",
];

// Текст от начала `head` до парной закрывающей скобки (и `;`, если он сразу за ней).
export function sliceBlock(src, head) {
  const start = src.indexOf(head);
  if (start === -1) throw new Error(`not found: ${head}`);
  const open = src.indexOf("{", start);
  let depth = 0;
  for (let i = open; i < src.length; i++) {
    if (src[i] === "{") depth++;
    else if (src[i] === "}") {
      depth--;
      if (depth === 0) {
        let end = i + 1;
        if (src[end] === ";") end++;
        return src.slice(start, end);
      }
    }
  }
  throw new Error(`unbalanced: ${head}`);
}

export function extractAll(src) {
  const blocks = { CONFIG: sliceBlock(src, "const CONFIG = {") };
  for (const name of FUNCTIONS) {
    // "\n" перед "function" — только объявления верхнего уровня
    blocks[name] = sliceBlock(src, `\nfunction ${name}(`).slice(1);
  }
  return blocks;
}

export function buildCore(src) {
  const b = extractAll(src);
  return [
    "// AUTO-GENERATED by tools/build-core.mjs from ../app.js — DO NOT EDIT BY HAND.",
    "// Функции ниже скопированы из app.js побайтно; проверка: tests/core-identity.test.mjs.",
    "let historicalTrades = [];",
    "let candleSeries = null;",
    'let activeStrategy = "wsb";',
    "let wsbCurrentState = null;",
    "",
    b.CONFIG,
    "",
    ...FUNCTIONS.map((n) => b[n] + "\n"),
    "// Оригинальный updateTradeMarkers рисует в candleSeries; здесь он отдаёт метки массивом.",
    "export function computeMarkers(data, strategy, wsbState) {",
    "  let out = [];",
    "  candleSeries = { setMarkers: (m) => { out = m; } };",
    "  activeStrategy = strategy;",
    "  historicalTrades = [];",
    "  wsbCurrentState = wsbState || null;",
    "  updateTradeMarkers(data);",
    "  candleSeries = null;",
    "  return out;",
    "}",
    "",
    `export { CONFIG, ${FUNCTIONS.join(", ")} };`,
    "",
  ].join("\n");
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  fs.mkdirSync(path.dirname(CORE_JS), { recursive: true });
  fs.writeFileSync(CORE_JS, buildCore(fs.readFileSync(APP_JS, "utf8")));
  console.log(`written ${CORE_JS}`);
}
